import uuid
from datetime import datetime

from sqlalchemy import BigInteger, CheckConstraint, DateTime, Integer, LargeBinary, Uuid, func
from sqlalchemy.orm import Mapped, mapped_column

from app.config import MAX_BLOB_BYTES_LIMIT
from app.database import Base


class VaultRecord(Base):
    """
    User's encrypted vault

    The server operates on a zero-knowledge basis: encrypted_blob is a byte sequence
    in the KTLN… format (Argon2id header + AES-256-GCM ciphertext) generated on the device.
    The decryption key is never stored on the server
    """

    __tablename__ = "vault_records"
    __table_args__ = (
        CheckConstraint(f"blob_size <= {MAX_BLOB_BYTES_LIMIT}", name="blob_size_limit"),
        CheckConstraint("version >= 0", name="version_non_negative"),
    )

    # Sync code: a random UUIDv4 generated by the server
    token: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)

    # NULL immediately after registration, until the first PUT uploads the vault
    encrypted_blob: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)

    # Version for optimistic locking: +1 on each successful update
    version: Mapped[int] = mapped_column(BigInteger, nullable=False, default=0, server_default="0")

    blob_size: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )
